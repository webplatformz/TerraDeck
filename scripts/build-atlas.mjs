import { readFileSync, writeFileSync } from 'node:fs'
import { COUNTRIES as shapes } from './geo/countries.mjs'
import { CONTEXT_ONLY_FEATURES, DEFERRED, ORIGINAL_DEFERRED } from './atlas/policy.mjs'

const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'))
const write = (path, value) => writeFileSync(new URL(path, import.meta.url), `${JSON.stringify(value, null, 2)}\n`)
const source = read('./atlas/snapshot.json')
const reference = read('./rarity/snapshot.json')
const initial = read('./atlas/initial-roster.json')
const expected = [...reference.countries.map(c => c.id), 'ps', 'va']
if (new Set(expected).size !== 195 || source.countries.length !== 195 ||
  expected.some(id => !source.countries.some(c => c.id === id))) throw new Error('Expected exact 195-candidate source')
// Keep the published 190-card catalog and numbering for archival saves and fixed rarity.
const order = [...initial, ...expected.filter(id => !initial.includes(id) && !(id in ORIGINAL_DEFERRED)).sort()]
if (order.length !== 190 || new Set(order).size !== 190) throw new Error('Expected 190 unique catalog countries')
const catalog = order.map(id => {
  const entries = shapes.filter(([name, iso]) => iso.toLowerCase() === id && !CONTEXT_ONLY_FEATURES.includes(name))
  if (entries.length !== 1) throw new Error(`Expected one canonical feature: ${id}`)
  const [mapName, , continent] = entries[0]
  return { id, mapName, continent }
})
const roster = catalog.filter(c => !(c.id in DEFERRED))
if (roster.length !== 168 || Object.keys(DEFERRED).length !== 27) throw new Error('Expected 168 playable countries and 27 exclusions')
write('./atlas/roster.json', roster)
write('../src/data/generated/playable-country-ids.json', roster.map(c => c.id))
write('./rarity/roster.json', order)

// Conventional German spellings; other capital proper names retain their source spelling.
const capitalDE = {
  Yerevan: 'Jerewan', Vienna: 'Wien', Brussels: 'Brüssel', Prague: 'Prag', Copenhagen: 'Kopenhagen',
  'Guatemala City': 'Guatemala-Stadt', Tehran: 'Teheran', Baghdad: 'Bagdad', 'Kuwait City': 'Kuwait-Stadt',
  Luxembourg: 'Luxemburg', 'Ulan Bator': 'Ulaanbaatar', Muscat: 'Maskat', 'Panama City': 'Panama-Stadt',
  Warsaw: 'Warschau', Pyongyang: 'Pjöngjang', Lisbon: 'Lissabon', Bucharest: 'Bukarest',
  Moscow: 'Moskau', Riyadh: 'Riad', Singapore: 'Singapur', 'City of San Marino': 'San Marino',
  Belgrade: 'Belgrad', Damascus: 'Damaskus', Dushanbe: 'Duschanbe', Ashgabat: 'Aschgabat',
  Kyiv: 'Kyjiw', Tashkent: 'Taschkent', "Sana'a": 'Sanaa', 'South Tarawa': 'Süd-Tarawa',
  Bishkek: 'Bischkek', 'Nicosia': 'Nikosia',
}
const names = {
  en: { cd: 'Democratic Republic of the Congo', cg: 'Republic of the Congo', ci: "Côte d’Ivoire" },
  de: { cd: 'Demokratische Republik Kongo', cg: 'Republik Kongo', by: 'Belarus', sz: 'Eswatini', tl: 'Timor-Leste' },
}
const capitalNotes = {
  ps: ['Ramallah (administrative seat)', 'Ramallah (Verwaltungssitz)'],
  za: ['Pretoria (executive)', 'Pretoria (Exekutive)'],
  sz: ['Mbabane (administrative)', 'Mbabane (Verwaltung)'],
}
for (const lang of ['en', 'de']) {
  const locale = read(`../src/i18n/locales/${lang}.json`)
  for (const c of source.countries.filter(c => order.includes(c.id))) {
    if (locale.countries[c.id]) continue
    const name = names[lang][c.id] ?? (lang === 'en' ? c.name : c.germanName)
    const capital = capitalNotes[c.id]?.[lang === 'en' ? 0 : 1] ??
      (lang === 'en' ? c.capital[0] : capitalDE[c.capital[0]] ?? c.capital[0])
    const neighbors = c.borders.map(code => source.countries.find(n => n.cca3 === code))
      .filter(n => n && order.includes(n.id)).slice(0, 2)
      .map(n => names[lang][n.id] ?? (lang === 'en' ? n.name : n.germanName))
    const fact = c.landlocked
      ? (lang === 'en' ? 'A landlocked country with no coastline on the open sea.' : 'Ein Binnenstaat ohne Küste am offenen Meer.')
      : neighbors.length
        ? (lang === 'en' ? `Its land neighbours include ${neighbors.join(' and ')}.` : `Zu seinen Landnachbarn ${neighbors.length === 1 ? 'gehört' : 'gehören'} ${neighbors.join(' und ')}.`)
        : (lang === 'en' ? 'An island country without land borders to another country.' : 'Ein Inselstaat ohne Landgrenzen zu einem anderen Land.')
    locale.countries[c.id] = { name, capital, fact }
  }
  write(`../src/i18n/locales/${lang}.json`, locale)
}
write('../src/data/generated/country-additions.json', catalog.filter(c => !initial.includes(c.id)).map(c => {
  const metadata = source.countries.find(s => s.id === c.id)
  return { ...c, population: metadata.population, areaKm2: metadata.areaKm2 }
}))
writeFileSync(new URL('../src/data/flags.ts', import.meta.url), `// Generated by scripts/build-atlas.mjs; one shared flag resolver.\nconst urls = import.meta.glob('/node_modules/flag-icons/flags/4x3/{${order.join(',')}}.svg', {\n  eager: true,\n  query: '?url',\n  import: 'default',\n}) as Record<string, string>\n\nexport function flagUrl(countryId: string): string | undefined {\n  return urls[\`/node_modules/flag-icons/flags/4x3/\${countryId}.svg\`]\n}\n`)
console.log(`Built ${roster.length} playable entries, ${Object.keys(DEFERRED).length} deferred; retained original ${initial.length}`)
